import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import "./globals.css";
import { StoreWrapper } from "./provider";
import { SpeedInsights } from "@vercel/speed-insights/next"
import {
  DESCRIPTION, GROUND, GROUND_DARK, ICON_512, NAME, SHORT_DESCRIPTION, TITLE, resolveSiteUrl,
} from "./siteMetadata";
import { themeScript } from "./themeScript";

/**
 * The one face (UI row 2): Nunito, self-hosted by `next/font`, in the four weights UI-SPEC §3.2
 * chose. Nunito itself runs 200-1000; nothing in `app/` asks for a weight outside these, and
 * `tests/typography.test.ts` holds that, so no text draws at a weight the page doesn't load.
 *
 * From the repository since U12 (NEXT-STEPS): `next/font/google` fetched it at every build, and
 * a Google response once failed one. The file is the Latin one Google serves for these four
 * weights, byte for byte (`fonts.gstatic.com/s/nunito/v32/XRXV3I6Li01BKofINeaBTMnFcQ.woff2`,
 * SHA-256 20fc9b6f...4798), with its licence beside it. It's the variable font, so the four
 * faces are one file at four weights, as Google's CSS declared them. The other four subsets
 * Google lists draw no character the app has.
 *
 * The binding's name is the family: Turbopack names a local font's stack after it, so this is
 * `Nunito`, and the stack `'Nunito', 'Nunito Fallback'`, as before (codex). The range is the
 * Latin subset's, from Google's CSS: the file holds a few code points outside it (codex), and
 * the range keeps this face to the characters it drew before.
 */
const Nunito = localFont({
  // Literals, one per weight: next/font reads its arguments at build time, not by running them.
  src: [
    { path: "./fonts/nunito-latin.woff2", weight: "600", style: "normal" },
    { path: "./fonts/nunito-latin.woff2", weight: "700", style: "normal" },
    { path: "./fonts/nunito-latin.woff2", weight: "800", style: "normal" },
    { path: "./fonts/nunito-latin.woff2", weight: "900", style: "normal" },
  ],
  variable: "--font-nunito",
  declarations: [{
    prop: "unicode-range",
    value: "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  }],
});

/**
 * What the game is called, everywhere it is named (spec P2-2, row 20b).
 *
 * This said "Create Next App" / "Generated by create next app" until row 20b, which is the
 * title in the browser tab, the name a bookmark takes, the heading a shared link shows in
 * a chat app, and the text a search engine indexes. For a game whose whole retention model
 * is "come back tomorrow", being unnamed in every one of those places is not cosmetic.
 *
 * `metadataBase` is what makes the OG image URL absolute, which is required: relative URLs
 * in Open Graph tags are not resolved by most crawlers, so the preview silently falls back
 * to no image at all. Where that base comes from — and why it must not be localhost — is
 * `siteMetadata.ts`, along with the strings this shares with the manifest.
 */
const siteUrl = resolveSiteUrl(process.env.NEXT_PUBLIC_SITE_URL)

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl),
  title: TITLE,
  description: DESCRIPTION,
  applicationName: NAME,
  appleWebApp: {
    // iOS reads this instead of the manifest, and the short name is what fits under an
    // icon on a home screen.
    capable: true,
    title: NAME,
    statusBarStyle: 'default',
  },
  openGraph: {
    type: 'website',
    siteName: NAME,
    title: TITLE,
    description: SHORT_DESCRIPTION,
    url: '/',
    images: [{ url: ICON_512, width: 512, height: 512, alt: 'A domino' }],
  },
  twitter: {
    card: 'summary',
    title: TITLE,
    description: SHORT_DESCRIPTION,
    images: [ICON_512],
  },
};

/**
 * `viewportFit: 'cover'` is what makes `env(safe-area-inset-*)` report anything but zero:
 * without it the page is laid out inside the safe area already and the insets are 0, so
 * the notch simply eats the board's width with nothing able to see it.
 *
 * Zoom is left enabled on purpose, and `userScalable` is left *unset* rather than set to
 * true: the default is already enabled, and an explicit `true` invites someone to flip it.
 * Banning zoom is the usual "fix" for layout that does not survive scaling -- the layout
 * suite proves this one does, at 50% through 200% -- and it takes pinch-zoom away from the
 * people who need it most.
 *
 * `themeColor` matches the board's ground so the browser's own chrome does not sit as a
 * bright white band above a grey page on a phone: one tag per scheme since UI row 1, each
 * that theme's ground. A player's own choice points both at its ground (`themeScript.ts`).
 */
export const viewport: Viewport = {
  viewportFit: 'cover',
  themeColor: [
    { media: '(prefers-color-scheme: light)', color: GROUND },
    { media: '(prefers-color-scheme: dark)', color: GROUND_DARK },
  ],
};

/** The theme a player chose, applied before the first paint (UI row 1; `themeScript.ts`). */
const THEME_SCRIPT = themeScript();

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    // `suppressHydrationWarning`: the theme script adds `data-theme` to this element before
    // React hydrates it, on purpose. It covers this element's own attributes only.
    <html lang="en" suppressHydrationWarning>
      <head>
        {/* In <head>, so the theme is set before <body> is parsed and anything is drawn.
            Next hoists its own tags above this one: the charset, viewport, stylesheet,
            scripts and metadata, the theme-color tags among them (measured, UI row 1). */}
        <script dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }} />
      </head>
      <body
        className={`${Nunito.variable} antialiased`}
      >
        {/* Inside <body>, not wrapping <html>: the provider is a client component, and
            handing it the document element pulls the whole store graph into every route's
            SSR module graph and makes <head> hoisting/streaming fragile. */}
        <StoreWrapper>
          {children}
        </StoreWrapper>
        <SpeedInsights />
      </body>
    </html>
  );
}
